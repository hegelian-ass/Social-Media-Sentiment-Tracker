# =========================================================
# NORMALIZATION
# =========================================================

def clean(value):
    if value is None:
        return ""
    if pd.isna(value):
        return ""
    return str(value).strip()


def norm_text(value):
    return re.sub(r"\s+", " ", clean(value)).lower()


def norm_url(value):
    return clean(value).split("?")[0].rstrip("/").lower()


def norm_platform(value):
    value = norm_text(value)

    if value in ("twitter", "x"):
        return "x"

    return value


def norm_date(value):
    if not clean(value):
        return ""

    parsed = pd.to_datetime(
        value,
        errors="coerce",
        dayfirst=True,
        utc=True
    )

    if pd.isna(parsed):
        return ""

    return parsed.strftime("%Y-%m-%d")


def is_true(value):
    return clean(value).lower() in (
        "true", "1", "yes", "y"
    )


def get_first_value(row, columns):
    """Return the first non-empty value from available columns."""

    for column in columns:
        value = clean(row.get(column, ""))

        if value and value.lower() not in ("nan", "none"):
            return value

    return ""


# =========================================================
# POST DATE
# =========================================================

def get_post_date(post):
    return norm_date(
        get_first_value(
            post,
            ["post_date", "timestamp", "created_time", "date"]
        )
    )


# =========================================================
# CSV LOADING
# =========================================================

def read_csv_if_exists(path):

    if not path.exists():
        print(f"Missing file, skipped: {path}")
        return None

    try:
        df = pd.read_csv(
            path,
            dtype=str,
            keep_default_na=False,
            encoding="utf-8-sig"
        )

        print(f"Loaded: {path} ({len(df)} rows)")
        return df

    except Exception as error:
        raise RuntimeError(
            f"Could not read {path}: {error}"
        ) from error


# =========================================================
# ISSUE DESCRIPTION BUILDER
# =========================================================

def get_issue_category(row):
    """
    Prefer the detailed category column generated by sentiment.py.
    Fall back to the older issue column.
    """

    return get_first_value(
        row,
        [
            "issue_categories",
            "issue_category",
            "issue"
        ]
    )


def get_issue_description(row):
    """
    Prefer major_issue_text because it contains the detailed
    explanation generated during sentiment analysis.
    """

    return get_first_value(
        row,
        [
            "major_issue_text",
            "issue_description",
            "issue_details",
            "issue"
        ]
    )


def build_issue_entry(row):
    """
    Format:
    Governance: SPO salary increment delays and unfulfilled
    demands — "What happened to SPOs salary increment"
    """

    comment = get_first_value(
        row,
        ["comment_text", "text", "message"]
    )

    category = get_issue_category(row)
    description = get_issue_description(row)

    if not comment:
        return ""

    if not category or category.lower() == "other":
        category = "Public Issue"

    # If the analysis already produced a detailed description,
    # retain it instead of replacing it with just the category.
    if description:
        description_normalized = norm_text(description)
        category_normalized = norm_text(category)

        if description_normalized.startswith(category_normalized + ":"):
            detail = description
        else:
            detail = f"{category}: {description}"
    else:
        detail = category

    # Avoid repeating the comment if it is already inside
    # the generated major_issue_text.
    if norm_text(comment) not in norm_text(detail):
        detail = f'{detail} — "{comment}"'

    return detail


# =========================================================
# UNIQUE ENTRIES
# =========================================================

def add_unique(items, entry):

    entry = clean(entry)

    if not entry:
        return

    # Prevent duplicate entries even if spacing differs.
    existing = {
        norm_text(item)
        for item in items
    }

    if norm_text(entry) not in existing:
        items.append(entry)


# =========================================================
# FIND EXISTING GOOGLE SHEET ROW
# =========================================================

def find_sheet_row(daily_data, platform, caption, date):

    candidates = []

    # Data begins at row 6.
    for row_number, row in enumerate(
        daily_data[5:],
        start=6
    ):

        if len(row) < 3:
            continue

        row_platform = norm_platform(row[1])
        row_caption = norm_text(row[2])
        row_date = norm_date(row[0])

        if (
            row_platform == norm_platform(platform)
            and row_caption == norm_text(caption)
        ):
            candidates.append((row_number, row_date))

    if date:
        exact_matches = [
            number
            for number, row_date in candidates
            if row_date == date
        ]

        if len(exact_matches) == 1:
            return exact_matches[0]

    blank_date_matches = [
        number
        for number, row_date in candidates
        if not row_date
    ]

    if len(blank_date_matches) == 1:
        return blank_date_matches[0]

    if len(candidates) == 1:
        return candidates[0][0]

    return None


# =========================================================
# VALIDATE INPUT FILES
# =========================================================

def validate_data(posts, comments, config):

    required_posts = [
        "caption",
        "post_url"
    ]

    required_comments = [
        "post_url",
        "comment_text",
        "sentiment"
    ]

    for column in required_posts:
        if column not in posts.columns:
            raise ValueError(
                f"{config['posts']} is missing column: {column}"
            )

    for column in required_comments:
        if column not in comments.columns:
            raise ValueError(
                f"{config['comments']} is missing column: {column}"
            )

    # Older files may not have these columns.
    defaults = {
        "issue": "",
        "issue_categories": "",
        "major_issue_text": "",
        "is_major_criticism": "false",
        "is_major_issue": "false",
    }

    for column, default in defaults.items():
        if column not in comments.columns:
            comments[column] = default

    return posts, comments


# =========================================================
# PROCESS ONE PLATFORM
# =========================================================

def process_platform(
    worksheet,
    daily_data,
    platform_key,
    config
):

    posts = read_csv_if_exists(config["posts"])
    comments = read_csv_if_exists(config["comments"])

    if posts is None or comments is None:
        return 0

    posts, comments = validate_data(
        posts,
        comments,
        config
    )

    # Normalize URLs.
    posts["_url"] = posts["post_url"].map(norm_url)
    comments["_url"] = comments["post_url"].map(norm_url)

    comments["sentiment"] = comments["sentiment"].map(
        lambda value: clean(value).capitalize()
    )

    updated = 0

    # Process each post separately.
    for url, group in comments.groupby(
        "_url",
        sort=False
    ):

        if not url:
            continue

        matching_posts = posts[
            posts["_url"] == url
        ]

        if matching_posts.empty:
            print(
                f"\n[{config['sheet_name']}] "
                f"No matching post found for URL: {url}"
            )
            continue

        post = matching_posts.iloc[0]

        date = get_post_date(post)
        caption = clean(post.get("caption", ""))

        matched_row = find_sheet_row(
            daily_data,
            config["sheet_name"],
            caption,
            date
        )

        if matched_row is None:
            print(
                f"\n[{config['sheet_name']}] "
                "No unique matching Daily Sheet row."
            )
            print("Caption:", caption[:120])
            print("Date:", date)
            continue

        # =============================================
        # SENTIMENT COUNTS
        # =============================================

        good_count = int(
            (group["sentiment"] == "Good").sum()
        )

        bad_count = int(
            (group["sentiment"] == "Bad").sum()
        )

        neutral_count = int(
            (group["sentiment"] == "Neutral").sum()
        )

        # =============================================
        # COLUMN H: ALL MAJOR NEGATIVE COMMENTS
        # =============================================

        major_bad = group[
            (group["sentiment"] == "Bad")
            & group["is_major_criticism"].map(is_true)
        ]

        bad_comments = []

        for _, row in major_bad.iterrows():
            comment = get_first_value(
                row,
                ["comment_text"]
            )

            add_unique(bad_comments, comment)

        bad_text = (
            "\n".join(
                f"{i}. {comment}"
                for i, comment in enumerate(
                    bad_comments,
                    start=1
                )
            )
            if bad_comments
            else "No major negative comment"
        )

        # =============================================
        # COLUMN I: DETAILED MAJOR PUBLIC ISSUES
        # =============================================

        issue_entries = []

        # Include all major criticism comments that also
        # represent an identified issue.
        for _, row in major_bad.iterrows():

            entry = build_issue_entry(row)

            add_unique(issue_entries, entry)

        # Include separately flagged major issues.
        # This captures Neutral requests, including VDG.
        for _, row in group.iterrows():

            if is_true(row.get("is_major_issue", "")):

                entry = build_issue_entry(row)

                add_unique(issue_entries, entry)

        issue_text = (
            "\n".join(
                f"{i}. {entry}"
                for i, entry in enumerate(
                    issue_entries,
                    start=1
                )
            )
            if issue_entries
            else "No major issue"
        )

        # =============================================
        # UPDATE ONLY COLUMNS F:J
        # =============================================

        # A:E are deliberately untouched.
        # Existing post dates, platform, captions,
        # likes and shares are preserved.

        worksheet.batch_update([

            {
                "range": f"F{matched_row}:G{matched_row}",
                "values": [[
                    good_count,
                    bad_count
                ]]
            },

            {
                "range": f"H{matched_row}:I{matched_row}",
                "values": [[
                    bad_text,
                    issue_text
                ]]
            },

            {
                "range": f"J{matched_row}",
                "values": [[neutral_count]]
            }

        ])

        updated += 1

        print(
            f"\n{config['sheet_name']} "
            f"post updated: row {matched_row}"
        )

        print(
            f"Good: {good_count} | "
            f"Bad: {bad_count} | "
            f"Neutral: {neutral_count}"
        )

        print(
            "Major negative comments:",
            len(bad_comments)
        )

        print(
            "Detailed major issues:",
            len(issue_entries)
        )

    return updated


# =========================================================
# MAIN UPLOAD FUNCTION
# =========================================================

def main():

    print("=" * 55)
    print("LOP SENTIMENT TRACKER - GOOGLE SHEETS UPLOADER")
    print("=" * 55)

    print("\nConnecting to Google Sheets...")

    client = gspread.service_account(
        filename=CREDENTIALS_FILE
    )

    spreadsheet = client.open(
        SPREADSHEET_NAME
    )

    worksheet = spreadsheet.worksheet(
        WORKSHEET_NAME
    )

    print("Google Sheets connection successful.")

    # Set the neutral count heading.
    worksheet.batch_update([

        {
            "range": "J4",
            "values": [["Neutral"]]
        },

        {
            "range": "J5",
            "values": [["Count"]]
        }

    ])

    # Read existing rows once.
    daily_data = worksheet.get_all_values()

    total_updated = 0

    for platform_key, config in PLATFORMS.items():

        print("\n" + "=" * 45)
        print(f"PROCESSING: {config['sheet_name'].upper()}")
        print("=" * 45)

        try:
            count = process_platform(
                worksheet,
                daily_data,
                platform_key,
                config
            )

            total_updated += count

        except Exception as error:

            print(
                f"\nERROR processing {config['sheet_name']}: "
                f"{error}"
            )

            # Continue with other platforms.
            continue

    print("\n" + "=" * 55)
    print("UPLOAD PROCESS COMPLETED")
    print("=" * 55)

    print("Total posts updated:", total_updated)

    print("=" * 55)


if __name__ == "__main__":
    main()
